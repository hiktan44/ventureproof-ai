type LanguageContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, values?: Record<string, string | number>) => string;
  moduleLabel: (key: ModuleKey) => string;
  moduleCopy: (key: ModuleKey) => string;
  statusLabel: (status: ModuleStatus) => string;
  experimentStatusLabel: (status: ExperimentStatus) => string;
  sourceKindLabel: (kind: SourceKind) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

function interpolate(value: string, values?: Record<string, string | number>) {
  if (!values) return value;
  return Object.entries(values).reduce((copy, [key, replacement]) => copy.replaceAll(`{${key}}`, String(replacement)), value);
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("tr");

  useEffect(() => {
    const stored = window.localStorage.getItem("ventureproof-language");
    if (stored === "tr" || stored === "en") setLanguageState(stored);
  }, []);

  const value = useMemo<LanguageContextValue>(() => {
    const translate = (key: string, values?: Record<string, string | number>) => {
      const entry = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
      return interpolate(entry, values);
    };
    return {
      language,
      setLanguage(next) {
        setLanguageState(next);
        window.localStorage.setItem("ventureproof-language", next);
        document.documentElement.lang = next;
      },
      t: translate,
      moduleLabel: (key) => translate(`module.${key}`),
      moduleCopy: (key) => translate(`module.${key}Copy`),
      statusLabel: (status) => translate(`status.${status}`),
      experimentStatusLabel: (status) => translate(`experiment.${status}`),
      sourceKindLabel: (kind) => translate(`source.${kind}`)
    };
  }, [language]);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useLanguage must be used inside LanguageProvider");
  return value;
}
